#!/usr/bin/env node
// Regenerates the @benzenejs/* -> source mappings that let TypeScript and Vitest resolve
// cross-package imports straight to `src/**/index.ts` during development, independent of each
// package's own "main"/"types" fields (which point at compiled `dist/` output for publishing).
// Without this, editing one package's source wouldn't be visible to a sibling package's typecheck
// or tests until `npm run build` had been re-run.
//
// Re-run this (`node scripts/sync-workspace-paths.mjs`) after adding, removing, or renaming a
// package under src/.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const srcDir = join(repoRoot, 'src');

const folders = readdirSync(srcDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const paths = {};
const aliasEntries = [];
for (const folder of folders) {
  const pkg = JSON.parse(readFileSync(join(srcDir, folder, 'package.json'), 'utf8'));
  const rel = `./src/${folder}/index.ts`;
  paths[pkg.name] = [rel];
  aliasEntries.push([pkg.name, rel]);
}

const tsconfigPath = join(repoRoot, 'tsconfig.json');
const tsconfig = JSON.parse(readFileSync(tsconfigPath, 'utf8'));
tsconfig.compilerOptions.paths = paths;
writeFileSync(tsconfigPath, JSON.stringify(tsconfig, null, 2) + '\n');

const aliasLines = [
  '// GENERATED by scripts/sync-workspace-paths.mjs — do not hand-edit.',
  '// Re-run that script after adding/removing/renaming a package under src/.',
  "import { join } from 'node:path';",
  '',
  'const repoRoot = new URL(\'..\', import.meta.url).pathname;',
  '',
  'export const workspaceAliases = {',
  ...aliasEntries.map(([name, rel]) => `  '${name}': join(repoRoot, ${JSON.stringify(rel)}),`),
  '};',
  '',
].join('\n');
writeFileSync(join(repoRoot, 'scripts', 'workspace-aliases.generated.mjs'), aliasLines);

console.log(`Synced ${folders.length} workspace path mappings.`);
